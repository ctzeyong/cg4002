def test_warrior_walks_at_lane_over_ten_seconds():
    m = started()
    assert m.gesture(1, "warrior", (0.1, 0.3)).unit_id == 1  # lat 0.3 is on a bridge's own line
    snap = run(m, 3)
    # 2 m / 10 s = 0.2 m/s, so 0.6 m = 0.3 of the lane
    assert unit(snap, 1).along == pytest.approx(0.1 + 0.3, abs=0.002)
    assert unit(snap, 1).lat == pytest.approx(0.3, abs=0.002)


def test_warrior_reaches_the_tower_in_about_ten_seconds():
    m = started()
    m.gesture(1, "warrior", (0.0, 0.3))
    first_attack = None
    for tick in range(1, 130):
        snap = m.tick(DT)
        if first_attack is None and unit(snap, 1).state == "Attacking":
            first_attack = tick
    # The stand-off is the tower radius plus clearance, 3D with the unit 0.1 m up: about 9 s
    assert 85 <= first_attack <= 100
    assert snap.tower_hp[1] < 1000
    assert unit(snap, 1).hp < 150  # the tower hits back at 15 per second


