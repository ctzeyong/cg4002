def test_lane_length_sets_arena_scale():
    # (L / 2) ** 0.5 clamped to 0.7 .. 1.8: a 4 m lane scales ranges by 1.414
    m = started(lane=4.0)
    m.gesture(1, "mage", (0.1, 0.0))
    assert m.snapshot().units[0].range == pytest.approx(0.35 * math.sqrt(2), abs=1e-6)
    far = started(lane=10.0)
    far.gesture(1, "mage", (0.1, 0.0))
    assert far.snapshot().units[0].range == pytest.approx(0.35 * 1.8, abs=1e-6)  # clamped


