def test_a_sleeping_unit_target_is_always_in_the_snapshot():
    # a unit whose target died this tick must not point at a unit the snapshot no longer lists
    m = started()
    m.gesture(1, "tank", (0.4, 0.3))
    m.gesture(2, "rogue", (0.55, 0.3))
    for _ in range(300):
        snap = m.tick(DT)
        ids = {u.id for u in snap.units}
        assert all(u.target is None or u.target in ids for u in snap.units)


