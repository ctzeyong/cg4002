"""Scenario tests for the match core. No MQTT. Run from this folder: pytest test_match.py

Expected numbers are worked from rules.json and Week11.md, not generated by running the C#. The
rules file has no tower radius until Vis measures it in Unity, so the tests use TEST_TOWER_RADIUS.
"""

import copy
import json
import math
import pathlib
import sys

import pytest

HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
import match  # noqa: E402

TEST_TOWER_RADIUS = 0.15
L = 2.0  # the reference lane: arena scale 1
W = 0.55 * L  # lane width in metres
DT = 0.1


def load_rules(**match_state):
    rules = json.loads((HERE / "rules.json").read_text(encoding="utf-8"))
    rules = copy.deepcopy(rules)
    rules["TowerController"]["TowerRadius"] = TEST_TOWER_RADIUS
    rules["MatchState"].update(match_state)
    return rules


def started(rules=None, lane=L):
    m = match.Match(rules or load_rules(), 1)
    m.start(lane)
    return m


def frozen(**extra):
    """Units never move, and both players start with full mana, so a spell's damage can be worked out exactly."""
    return started(load_rules(globalSpeedMultiplier=0, manaStart=10, **extra))


def run(m, seconds):
    snap = None
    for _ in range(round(seconds / DT)):
        snap = m.tick(DT)
    return snap


def unit(snap, uid):
    return next(u for u in snap.units if u.id == uid)


