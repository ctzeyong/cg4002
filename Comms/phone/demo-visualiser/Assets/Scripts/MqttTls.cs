using System;
using System.Collections.Generic;
using System.IO;
using System.Net.Security;
using System.Security.Cryptography.X509Certificates;
using UnityEngine;

namespace Comms.Visualiser
{
    /// <summary>
    /// The phone's half of the mTLS leg: load this device's identity, and decide whether
    /// to trust the broker that answers.
    ///
    /// The phone holds its OWN keypair. It never holds the laptop's, and the two are not
    /// interchangeable: mosquitto runs `use_identity_as_username true`, so the certificate
    /// CN becomes the MQTT username, and a phone presenting the relay's certificate would
    /// authenticate as `laptop-relay`. Separate certificates keep the two identities apart.
    ///
    /// Nothing here is packaged in the APK. Both files are pushed to the app's private
    /// storage with adb, the same pattern tunnelled-visualiser uses for SSH keys,
    /// and for the same reason: anyone with the APK can extract what is inside it.
    ///
    ///     adb push ca.crt               /sdcard/Android/data/&lt;package&gt;/files/ca.crt
    ///     adb push phone-visualiser.p12 /sdcard/Android/data/&lt;package&gt;/files/phone-visualiser.p12
    ///
    /// Generated by comms/laptop/make_certs.ps1 and checked by verify_certs.ps1.
    /// </summary>
    public static class MqttTls
    {
        public const string CaFileName = "ca.crt";

        // Two bundles, because one of them may not load. OpenSSL 3 writes PKCS#12 with
        // AES-256-CBC/PBKDF2 by default, which Mono cannot always unwrap; make_certs.ps1
        // therefore also emits a legacy-encrypted copy (PBE-SHA1-3DES, MAC SHA1). Try the
        // modern one first and fall back, then SAY WHICH ONE WORKED -- the answer decides
        // what gets pushed to the phone, and finding it out in the Editor is far cheaper
        // than finding it out over adb.
        public const string BundleFileName = "phone-visualiser.p12";
        public const string LegacyBundleFileName = "phone-visualiser-legacy.p12";

        // The bundles are exported with an empty password on purpose. The protection is
        // the app's private storage, not a passphrase: a password the app must know would
        // have to be compiled into the APK, which is the secret-in-the-APK problem mTLS
        // was chosen to avoid in the first place. Both spellings are tried because Mono
        // and .NET disagree about whether "no password" is "" or null.
        private static readonly string[] Passwords = { "", null };

        // Application.persistentDataPath is a Unity API and may only be read on the main
        // thread. The certificates are loaded from the MQTT session task, which is not it, so
        // the directory is captured once during Start and every path is built from the copy.
        // Reading it lazily instead would work in the Editor often enough to look correct and
        // then throw on the phone, which is the worst version of this bug.
        private static string _dataPath;

        /// <summary>Capture the data directory. Call from the main thread, before connecting.</summary>
        public static void CacheDataPath() => _dataPath = Application.persistentDataPath;

        private static string DataPath =>
            _dataPath ?? throw new InvalidOperationException(
                "MqttTls.CacheDataPath() must be called on the main thread before any path is used");

        public static string CaPath => Path.Combine(DataPath, CaFileName);
        public static string BundlePath => Path.Combine(DataPath, BundleFileName);
        public static string LegacyBundlePath => Path.Combine(DataPath, LegacyBundleFileName);

        /// <summary>
        /// Is there material to run mTLS with? File presence is the switch, so `adb push`
        /// turns TLS on and deleting the files turns it back off. That matters while the
        /// plaintext listener is still up: it stays alive until the phone
        /// works over TLS, because a broken phone leg and a broken handshake look
        /// identical from the phone.
        /// </summary>
        public static bool Available =>
            File.Exists(CaPath) && (File.Exists(BundlePath) || File.Exists(LegacyBundlePath));

        /// <summary>
        /// One line naming exactly which files are present and which are not.
        ///
        /// This mirrors mqtt_config.tls_params(), which raises a FileNotFoundError naming
        /// the missing files rather than letting the connection fail: a TLS failure with
        /// no explanation reads like a network fault, and on a phone there is no console
        /// to go and look. Put the answer on screen instead.
        /// </summary>
        public static string Describe()
        {
            // "present"/"NOT FOUND", never "ok". This line answers only "is the file there",
            // and a bundle can be present and still unreadable -- which is exactly what
            // happens to the OpenSSL 3 default bundle under Mono. Calling that "ok" invites
            // the reader to conclude it loaded, when the line that says what loaded is the
            // separate `identity ... (from <file>)` one.
            var parts = new List<string>
            {
                CaFileName + (File.Exists(CaPath) ? " present" : " NOT FOUND"),
                BundleFileName + (File.Exists(BundlePath) ? " present" : " NOT FOUND"),
                LegacyBundleFileName + (File.Exists(LegacyBundlePath) ? " present" : " NOT FOUND"),
            };
            return "files: " + string.Join(", ", parts) + $"  [{DataPath}]";
        }

        /// <summary>The pinned CA. Clients verify the broker against this and nothing else.</summary>
        public static X509Certificate2 LoadCa()
        {
            if (!File.Exists(CaPath))
                throw new FileNotFoundException($"CA certificate not found: {CaPath}");

            // Decoded by hand rather than handed to X509Certificate2(byte[]). PEM support in
            // that constructor varies across Mono, .NET and IL2CPP, and this is a fixed,
            // trivially checkable format. X509Certificate2.CreateFromPem would be the obvious
            // answer and is NOT available: it is .NET 5+, and this project is on
            // .NET Standard 2.1. That constraint is why the client half is PKCS#12 too.
            return new X509Certificate2(PemToDer(File.ReadAllText(CaPath)));
        }

        /// <summary>
        /// This phone's identity, with its private key. Tries the modern bundle, then the
        /// legacy one, and reports which succeeded through <paramref name="source"/>.
        /// </summary>
        /// <param name="attempts">
        /// Every bundle/password combination tried and what it said, including the ones that
        /// failed before a later one succeeded. Reported even on success on purpose: knowing
        /// that the modern bundle was *rejected* and the legacy one accepted is what decides
        /// which file gets pushed to the phone, and a silent fallback would hide it.
        /// </param>
        public static X509Certificate2 LoadClientCertificate(out string source, out List<string> attempts)
        {
            var failures = new List<string>();
            attempts = failures;

            foreach (var path in new[] { BundlePath, LegacyBundlePath })
            {
                if (!File.Exists(path)) continue;

                foreach (var password in Passwords)
                {
                    try
                    {
                        var bytes = File.ReadAllBytes(path);
                        var certificate = new X509Certificate2(bytes, password, X509KeyStorageFlags.Exportable);
                        if (!certificate.HasPrivateKey)
                        {
                            failures.Add($"{Path.GetFileName(path)}: loaded without a private key");
                            continue;
                        }
                        source = Path.GetFileName(path);
                        return certificate;
                    }
                    catch (Exception exc)
                    {
                        failures.Add($"{Path.GetFileName(path)}: {exc.GetType().Name} {exc.Message}");
                    }
                }
            }

            // Name every attempt. "Handshake failed" on a phone is close to undebuggable;
            // "both bundles refused, here is what each said" is not.
            throw new InvalidOperationException(
                "no usable client certificate. Tried: " + string.Join(" | ", failures));
        }

        /// <summary>
        /// Decide whether the server that answered is our broker.
        ///
        /// MQTTnet 4.3.7 has no WithTrustChain, so the CA cannot simply be handed over --
        /// this callback is the only way to pin a self-signed CA, not a stylistic choice.
        /// The device trust store will never contain our CA, so the platform's own verdict
        /// is always "untrusted root"; that one error is expected and is what we replace
        /// with an explicit check.
        ///
        /// What is NOT waived is the name check. The broker certificate carries IP SANs for
        /// 127.0.0.1 and the laptop's AP address precisely so the address actually dialled
        /// is proven, and accepting a mismatch would throw that away and make the SANs
        /// pointless.
        /// </summary>
        public static bool IsOurBroker(X509Certificate presented, SslPolicyErrors errors, X509Certificate2 pinnedCa)
        {
            if (presented == null || pinnedCa == null) return false;

            // Fatal regardless of pinning: no certificate at all, or one issued for a
            // different address than the one we connected to.
            if ((errors & SslPolicyErrors.RemoteCertificateNotAvailable) != 0) return false;
            if ((errors & SslPolicyErrors.RemoteCertificateNameMismatch) != 0) return false;

            using (var chain = new X509Chain())
            {
                // No revocation check: a self-signed CA publishes no CRL and no OCSP
                // responder, so the only possible outcome is a lookup that fails or hangs.
                chain.ChainPolicy.RevocationMode = X509RevocationMode.NoCheck;

                // Allows the build to succeed with a root the device does not trust -- which
                // is the whole situation. It does NOT waive expiry or a broken signature,
                // and the thumbprint comparison below is what actually grants trust.
                chain.ChainPolicy.VerificationFlags = X509VerificationFlags.AllowUnknownCertificateAuthority;
                chain.ChainPolicy.ExtraStore.Add(pinnedCa);

                if (!chain.Build(new X509Certificate2(presented))) return false;
                if (chain.ChainElements.Count == 0) return false;

                // The root of the built chain must be our CA, by thumbprint. Comparing the
                // issuer NAME instead would accept any certificate claiming to be signed by
                // "B16 Comms CA" -- which is exactly the forgery a foreign-CA test
                // proved the broker rejects in the other direction.
                var root = chain.ChainElements[chain.ChainElements.Count - 1].Certificate;
                return string.Equals(root.Thumbprint, pinnedCa.Thumbprint, StringComparison.OrdinalIgnoreCase);
            }
        }

        private static byte[] PemToDer(string pem)
        {
            const string begin = "-----BEGIN CERTIFICATE-----";
            const string end = "-----END CERTIFICATE-----";

            var start = pem.IndexOf(begin, StringComparison.Ordinal);
            var stop = pem.IndexOf(end, StringComparison.Ordinal);
            if (start < 0 || stop < 0 || stop < start)
                throw new InvalidOperationException(
                    "CA file is not PEM: no BEGIN/END CERTIFICATE block found");

            var body = pem.Substring(start + begin.Length, stop - start - begin.Length);
            return Convert.FromBase64String(body.Replace("\r", "").Replace("\n", "").Trim());
        }
    }
}
